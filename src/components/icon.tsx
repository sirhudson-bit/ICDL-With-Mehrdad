export function getIcon(name: string | null | undefined): LucideIcon {
  if (!name) return BookOpen;
  return ICONS[name] ?? BookOpen;
}

type IconBubbleProps = {
  name: string;
  className?: string;
  size?: "sm" | "md" | "lg";
};

const BUBBLE_SIZES = {
  sm: { wrapper: "size-9 rounded-xl", icon: 18 },
  md: { wrapper: "size-12 rounded-2xl", icon: 22 },
  lg: { wrapper: "size-14 rounded-2xl", icon: 26 },
} as const;

/** Icon inside a soft tinted square — the visual signature of courseModule cards. */
export function IconBubble({ name, className, size = "md" }: IconBubbleProps) {
  const Icon = getIcon(name);
  const config = BUBBLE_SIZES[size];

  return (
    <span
      className={cn(
        "tone-icon inline-flex shrink-0 items-center justify-center",
        config.wrapper,
        className,
      )}
      aria-hidden="true"
    >
      <Icon size={config.icon} strokeWidth={2} />
    </span>
  );
}
